#!/usr/bin/env python3
"""Recover literal YTPDB arrays and exact segment-color doubles from verified data.

This supplements (and does not overwrite) the original decompiler evidence.
The generated includes contain real Objective-C, not decompiler pseudocode.
"""
import hashlib
import json
from pathlib import Path
import re
import struct
from inventory import MachO

REPO = Path(__file__).resolve().parents[2]
ROOT = REPO / 'recovery'


def main():
    data = (REPO / '.recovery-work/arm/YTLite.dylib').read_bytes()
    manifest = next(p for p in json.loads((ROOT / 'evidence/packages.json').read_text())
                    if p['package'].endswith('iphoneos-arm.deb'))
    digest = hashlib.sha256(data).hexdigest()
    if digest != manifest['binary_sha256']:
        raise RuntimeError('Input binary hash differs from the supplied package.')
    macho = MachO(data)
    decoded = {int(x['address'], 16): x['value'] for x in
               json.loads((ROOT / 'evidence/decoded-strings.json').read_text())}
    decoded_bytes = {}
    for line in (ROOT / 'evidence/decoded-bytes.tsv').read_text().splitlines()[1:]:
        address, byte, instruction = line.split('\t')
        decoded_bytes[int(address, 16)] = int(byte, 16)
    constants = {}
    for entry in json.loads((ROOT / 'evidence/arm-cfstrings.json').read_text()):
        address = int(entry['address'], 16)
        wide = bool(macho.ptr(address + 8) & 0x10)
        constants[address] = entry['value'] if wide else decoded.get(macho.ptr(address + 16), entry['value'])

    def constant_at(address):
        if address in constants:
            return constants[address]
        # Obfuscated CFString records also live in __data, outside __cfstring.
        # Overlay only byte writes whose values and instruction provenance were
        # recovered independently; decode wide strings using their actual flags.
        wide = bool(macho.ptr(address + 8) & 0x10)
        pointer, length = macho.ptr(address + 16), macho.ptr(address + 24)
        if length > 10000:
            raise ValueError(f'Unexpected CFString length at {address:#x}: {length}')
        raw = bytes(decoded_bytes[p] if p in decoded_bytes else data[macho.off(p)]
                    for p in range(pointer, pointer + length * (2 if wide else 1)))
        return raw.decode('utf-16-le' if wide else 'utf-8')
    evidence = (ROOT / 'classes/YTPDB.c').read_text()
    pieces = re.split(r'// \+\[YTPDB (\w+)\], (0x[0-9a-f]+)', evidence)
    arrays = {}
    expected = {'thanks': 62, 'clip': 53, 'report': 67, 'hype': 68, 'stopAds': 69}
    source = ['// Generated by recover_support_constants.py; do not hand-edit.',
              '// Binary SHA-256: ' + digest, '']
    for index in range(1, len(pieces), 3):
        selector, address, body = pieces[index:index + 3]
        if selector not in expected:
            continue
        slots = {}
        for match in re.finditer(r'\b\w+Stack_([0-9a-f]+) = (@"(?:\\.|[^"\\])*"|&PTR____CFConstantStringClassReference_[0-9a-f]+);', body):
            offset, expression = match.groups()
            if expression.startswith('@'):
                value = json.loads(expression[1:])
            else:
                value = constant_at(int(expression.rsplit('_', 1)[1], 16))
            if not value or '\x00' in value or '\ufffd' in value:
                raise ValueError(f'Unresolved constant in {selector}: {expression}')
            slots[int(offset, 16)] = value
        call = re.search(r'@selector\(arrayWithObjects:count:\),\s*&\w+Stack_([0-9a-f]+),\s*(0x[0-9a-f]+|\d+)\)', body)
        if call is None:
            raise ValueError(f'Array construction not found: {selector}')
        base, count = int(call[1], 16), int(call[2], 0)
        if count != expected[selector]:
            raise ValueError(f'Array count changed: {selector}')
        values = [slots[base - 8 * i] for i in range(count)]
        arrays[selector] = {'implementation': address, 'count': count, 'values': values}
        source.extend([f'// +[YTPDB {selector}], {address}.', f'+ (NSArray *){selector} {{', '    return @['])
        source.extend('        @' + json.dumps(value, ensure_ascii=False) + ',' for value in values)
        source.extend(['    ];', '}', ''])
    if set(arrays) != set(expected):
        raise ValueError('Not all five packaged string arrays were recovered.')
    support = ROOT / 'source/Support'
    support.mkdir(parents=True, exist_ok=True)
    (support / 'YTPDBStrings.inc').write_text('\n'.join(source))

    # Argument order and constant addresses from -colorForSegment:, 0x1eb10c.
    component_addresses = {
        'sponsor': (0xc4c3f0, 0xc4c3f8, 0xc4c400, 0xc4c2f8),
        'intro': (0xc4c408, 0xc4c410, 0xc4c418, 0xc4c368),
        'endcards': (0xc4c318, 0xc4c318, 0xc4c420, 0xc4c368),
        'interaction': (0xc4c428, 0xc4c430, 0xc4c438, 0xc4c368),
        'selfpromo': (1.0, 1.0, 0xc4c440, 0xc4c368),
        'nonmusic': (0xc4c448, 0xc4c450, 0xc4c458, 0xc4c368),
        'preview': (0xc4c400, 0xc4c460, 0xc4c468, 0xc4c368),
        'highlight': (0xc4c470, 0xc4c478, 0xc4c480, 0xc4c368),
        'jokes': (0xc4c488, 0xc4c490, 0xc4c498, 0xc4c368),
    }
    colors, lines = {}, ['// Generated from -[YTLUserDefaults colorForSegment:], 0x1eb10c.',
                         '// Hexadecimal floating literals preserve the original binary doubles.',
                         'static NSDictionary<NSString *, UIColor *> *YTLSegmentColors(void) {',
                         '    return @{']
    for name, locations in component_addresses.items():
        values = [location if isinstance(location, float) else struct.unpack_from('<d', data, macho.off(location))[0]
                  for location in locations]
        colors[name] = {'locations': [hex(x) if isinstance(x, int) else x for x in locations],
                        'components': values, 'hex_components': [value.hex() for value in values]}
        r, g, b, a = [value.hex() for value in values]
        lines.append(f'        @"{name}": [UIColor colorWithRed:{r} green:{g} blue:{b} alpha:{a}],')
    for name in ('mainProgress', 'gradientProgress', 'scrubberColor'):
        colors[name] = {'expression': '[UIColor redColor]'}
        lines.append(f'        @"{name}": [UIColor redColor],')
    lines.extend(['    };', '}', ''])
    (support / 'YTLSegmentColors.inc').write_text('\n'.join(lines))
    report = {'binary_sha256': digest, 'arrays': arrays, 'colors': colors}
    (ROOT / 'evidence/support-constants.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
    print('Recovered five ordered string arrays (' + str(sum(x['count'] for x in arrays.values())) + ' entries) and twelve segment colors.')
    # Small branch tables needed for manual review of truncated functions. The
    # booleans indexing these tables must be established separately from code.
    for base, key in ((0x1159228, 0x20d8821e), (0x11a93d8, 0x979a6adb), (0x11a90c0, 0x3e184e7c),
                      (0x11a90e0, 0x5d87c92d), (0x11a90f8, 0x382036cb),
                      (0x11cb1b8, 0x4b0ce127), (0x11cb208, 0xa6bb2bb8)):
        delta = struct.unpack('<i', struct.pack('<I', macho.u32(macho.off(base + 16)) ^ key))[0]
        targets = [macho.ptr(base + i * 8) - delta for i in range(2)]
        if not all(0x8000 <= target < 0x280000 and target % 4 == 0 for target in targets):
            raise ValueError(f'Unexpected branch destinations at {base:#x}: {targets}')
        print(f'Table {base:#x}: index 0 -> {targets[0]:#x}, index 1 -> {targets[1]:#x}')
    for name, entry in colors.items():
        print(name, entry.get('components', entry.get('expression')))


if __name__ == '__main__':
    main()
