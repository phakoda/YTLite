#!/usr/bin/env python3
"""Recover the 49-entry defaults dictionary from its decompiled stack arrays."""
import argparse
import json
from pathlib import Path
import re
from inventory import MachO

def recover(binary,root):
    m=MachO(binary)
    decoded={int(x['address'],16):x['value'] for x in json.loads((root/'evidence/decoded-strings.json').read_text())}
    env={'param_1':'self'};last=None
    def literal(expr):
        expr=re.sub(r'^\([^)]*\)\s*','',expr.strip())
        if expr in env:return env[expr]
        if expr.startswith('&PTR____CFConstantStringClassReference_'):
            addr=int(expr.rsplit('_',1)[1],16);ptr=m.ptr(addr+16)
            return '@'+json.dumps(decoded.get(ptr,m.string(ptr)),ensure_ascii=False)
        if expr.startswith('PTR_s_'):
            return m.string(m.ptr(int(expr.rsplit('_',1)[1],16)))
        if expr.startswith('PTR_YTPDB_'):return 'YTPDB'
        if expr.startswith('&'):return ('array',expr[1:])
        if re.fullmatch(r'(?:0x[0-9a-f]+|[0-9]+)',expr):return int(expr,0)
        return expr
    def array(pointer,count):
        if not isinstance(pointer,tuple):raise ValueError(pointer)
        name=pointer[1];prefix,offset=name.rsplit('_',1)
        return [env['stack_'+format(int(offset,16)-8*i,'x')] for i in range(count)]
    for statement in (root/'decompiled/001e6b88.c').read_text().split(';'):
        statement=statement.strip()
        call=re.search(r'(?:(\w+) = )?_objc_msgSend\((.*?)\)\s*$',statement,re.S)
        if call:
            args=[literal(x.strip()) for x in call[2].split(',')]
            receiver,selector,*parameters=args
            if selector in ['numberWithBool:','numberWithInt:','numberWithUnsignedInteger:']:
                last=('@YES' if parameters[0] else '@NO') if selector=='numberWithBool:' else '@'+str(parameters[0]) if isinstance(parameters[0],int) else '@('+str(parameters[0])+')'
            elif selector=='arrayWithObjects:count:':last='@['+', '.join(array(*parameters))+']'
            elif selector=='dictionaryWithObjects:forKeys:count:':
                vals=array(parameters[0],parameters[2]);keys=array(parameters[1],parameters[2])
                return [dict(key=k,value=v) for k,v in zip(keys,vals)]
            else:
                if parameters:last='['+str(receiver)+' '+str(selector).split(':')[0]+':'+str(parameters[0])+']'
                else:last='['+str(receiver)+' '+str(selector)+']'
            if call[1]:env[call[1]]=last
            continue
        assign=re.search(r'(\w+) = (.*?)\s*$',statement,re.S)
        if assign:
            left,right=assign.groups()
            env[left]=last if right=='_objc_retainAutoreleasedReturnValue()' else literal(right)
            if 'Stack_' in left:env['stack_'+left.rsplit('_',1)[1]]=env[left]
    raise ValueError('Defaults dictionary call not found')

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('binary',type=Path);p.add_argument('--root',type=Path,default=Path('recovery'));a=p.parse_args()
    result=recover(a.binary.read_bytes(),a.root)
    # The decompiler omits this live x2 argument. The original instructions at
    # 0x1eaae4/0x1eaae8 load x2 = 0x11bbca0, the scrubberColor CFString.
    m=MachO(a.binary.read_bytes())
    assert m.u32(m.off(0x1eaae4))==0xb0007e82 and m.u32(m.off(0x1eaae8))==0x91328042
    for entry in result:
        if entry['key']=='@"scrubberColor"':entry['value']='[self colorForSegment:@"scrubberColor"]'
    (a.root/'evidence/defaults.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
    out=a.root/'source';out.mkdir(exist_ok=True)
    lines=['// Reconstructed from -[YTLUserDefaults registerDefaults], 5.2.2 VA 0x1e6b88.',
           '// Generated by recovery/tools/recover_defaults.py. Used by the actual class.',
           '#import "../../Utils/YTLUserDefaults.h"',
           '#import "Support/YTPDB.h"',
           '#import "Support/YTLRecoveredDefaults.h"','',
           'NSDictionary *YTLRecoveredDefaultValues(YTLUserDefaults *defaults) {',
           '    NSString *privateUserID = [defaults sbPrivateUserID];',
           '    NSString *publicUserID = [defaults sbPublicUserID:privateUserID];',
           '    return @{']
    for entry in result:
        value=entry['value'].replace('[self sbPublicUserID:[self sbPrivateUserID]]','publicUserID').replace('[self sbPrivateUserID]','privateUserID')
        value=value.replace('[self ', '[defaults ')
        lines.append(f'        {entry["key"]}: {value},')
    lines+=['    };','}','']
    (out/'YTLUserDefaults+RecoveredDefaults.m').write_text('\n'.join(lines))
    print(f'Recovered {len(result)} defaults, preserving dynamic colors, languages and user IDs.')

if __name__=='__main__':main()
